  String enumText(String value) {
    const keys = {
      'todo': 'todo',
      'in_progress': 'inProgress',
      'done': 'done',
      'low': 'low',
      'medium': 'medium',
      'high': 'high',
      'urgent': 'urgent',
    };
    return text(keys[value] ?? value);
  }

  String? emailError(String? value) {
    if (value == null || value.trim().isEmpty) return text('emailRequired');
    return RegExp(r'^[^@\s]+@[^@\s]+\.[^@\s]+$').hasMatch(value.trim())
        ? null
        : text('invalidEmail');
  }

  String? passwordError(String? value) {
    if (value == null || value.isEmpty) return text('passwordRequired');
    return value.length < 8 ? text('passwordLength') : null;
  }
